const en = pl.map((template) => {
  const m = meta[template.id];
  let content = template.content;
  for (const [from, to] of contentReplacements) {
    content = content.split(from).join(to);
  }
  return {
    ...template,
    name: m?.name ?? template.name,
    description: m?.description ?? template.description,
    content,
  };
});

